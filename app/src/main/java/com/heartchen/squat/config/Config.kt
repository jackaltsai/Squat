    const val CHEST_EXPANSION_TURN_CONFIRM_FRACTION = 0.08f
    const val CHEST_EXPANSION_RETURN_FRACTION = 0.20f

    // ---- M8 上肢動作的框位引導 ----
    // 下肢動作用「髖-踝距離佔畫面高度」判斷遠近，上肢動作拿不到腳踝（也不需要），
    // 改用肩寬佔畫面寬度。

    /** 肩寬佔畫面寬度低於此比例視為太遠。 */
