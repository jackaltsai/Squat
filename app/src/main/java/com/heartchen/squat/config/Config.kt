    // ---- M8 擴胸推掌 ----
    // 從單一前視角相機，**向前推掌幾乎沒有位移**（手往鏡頭方向伸，2D 投影幾乎不動），
    // 所以可靠量到的只有「雙臂向兩側打開」那一半 —— 而那恰好就是擴胸本身。
    // 訊號取左右手腕的水平間距，以校正時的肩寬正規化。

    /**
     * 判準取「幾何最大間距」的此比例。
     *
     * 幾何最大間距 = 肩寬 + 2 × 手臂長（雙臂完全側平舉時的腕距），
     * 兩個量都在站姿校正時量到，所以判準完全錨在使用者自己的身體尺寸上，
     * 不是一個憑感覺訂的絕對值。取 0.6 時 target ≈ 1.38 個肩寬，
