    // 見 `HeelRaiseSignal` 與 `PoseDetectionScreen` 的倒數重新取基準。

    /**
     * 判準小於此值的動作，必須在**倒數期間重新量一次基準**，不能沿用站姿校正的那一份。
     *
     * 理由是普遍的，不是踮腳尖專屬：使用者在站姿校正與訓練之間移動幾個百分點是常態
     * （實測一場退了 6%，腿長 291.9 → 274.2px，基準誤差達腿長 11%）。
     * 判準大的動作無傷 —— 高抬腿的判準是 0.545 個腿長，同樣的誤差只佔五分之一；
     * 判準小的動作會被整個蓋掉 —— 踮腳尖的 0.06 比誤差還小，實測計次是 **0 下**。
     *
     * 六個動作的判準：深蹲家族 null（分母是 Duser）、上肢 1.37~2.24、
     * 高抬腿 0.545、踮腳尖 **0.06**。0.10 把踮腳尖單獨分出來，
     * 而且日後任何小幅度動作都會自動套用 ——
     * **綁在「判準有多小」這個成因上，不綁在動作名稱上。**
     */
    const val COUNTDOWN_REBASELINE_TARGET_MAX = 0.10f

    /**
     * 判準：髖上升到站姿腿長的此比例視為完成一次標準踮腳（`p = 1.0`）。
     *
     * 兩條互相獨立的推導都指向 0.06：
     * - **實測**：刻意踮到最高時振幅是腿長的 0.075~0.079（兩場、兩腳，σ=0.002）。
     *   0.06 是其 77%，即「踮到自己最高的八成」。
     * - **解剖學**：踝完全屈曲約 50°，前足槓桿約 15cm → 上升約 11.5cm；
     *   成人髖-踝約 83cm → 完全活動度約 0.139 個腿長。0.06 是其 43%，
     *   對長者是安全而非極限的幅度。
     *
     * ⚠️ 與 [CHEST_EXPANSION_TARGET_FRACTION_OF_FULL] 同樣的地位：**唯一的旋鈕，
     * 且只在單一受試者上驗過**。整場都紅就調低、整場都綠（失去鑑別力）就調高，
     * 調之前先用研究模式錄一場跑 `tools/analyze_frames.py`。
     */
    const val HEEL_RAISE_TARGET_RISE_RATIO = 0.06f

    /** 進度超過判準的此比例視為開始踮起。 */
    const val HEEL_RAISE_ENTER_FRACTION = 0.30f

    /**
     * 須從峰值回退判準的此比例才算轉折（開始放下）。
     *
     * 刻意比其他動作的 0.08 大 —— 0.08 × 0.06 = 0.0048 個腿長，在實測的雜訊底
     * （0.003~0.011）同量級，停在最高點時會被雜訊湊出假轉折。
     * 0.20 × 0.06 = 0.012，是雜訊的 1~4 倍。
     */
    const val HEEL_RAISE_TURN_CONFIRM_FRACTION = 0.20f

    /** 進度低於判準的此比例視為腳跟已落地，計次 +1。 */
    const val HEEL_RAISE_RETURN_FRACTION = 0.20f

    /**
     * 站姿量到的「腳尖-髖距離 ÷ 腿長」合理區間。
     *
     * 實測 1.155 與 1.180（兩場）。這個量**主要由拍攝幾何決定**而非解剖
     * （站姿時腳尖比腳踝低 80px ≈ 23cm，而腳踝離地只有 7cm，差額是透視），
     * 所以區間放寬到 1.05~1.45：它只是用來擋掉「校正時人就已經踮著」或
     * 關鍵點明顯亂掉的場次，不是精確的解剖學檢查。
     */
    const val CALIBRATION_MIN_TOE_TO_HIP_RATIO = 1.05f
    const val CALIBRATION_MAX_TOE_TO_HIP_RATIO = 1.45f

    /**
     * 踮腳尖專用的最小「髖-踝距離佔畫面高度」比例。
     *
     * 一般下肢動作用 [FRAMING_TOO_FAR_RATIO]（0.20）就夠，但踮腳尖的位移只有
     * 腿長的 6~8%，**訊噪比對拍攝距離極度敏感**：實測腿長 226px 時只有 7.1，
     * 277px 時是 25.0。0.20 的門檻完全擋不住前者（226/640 = 0.35 照樣通過）。
     *
     * 0.40 已確認可同時滿足「全身入鏡」—— 驗證通過的那場正是 0.433。
     */
    const val FRAMING_HEEL_RAISE_MIN_LEG_SPAN_RATIO = 0.40f

    // ---- M8 上肢動作的框位引導 ----
    // 下肢動作用「髖-踝距離佔畫面高度」判斷遠近，上肢動作拿不到腳踝（也不需要），
    // 改用肩寬佔畫面寬度。

    /** 肩寬佔畫面寬度低於此比例視為太遠。 */
    const val FRAMING_SHOULDER_WIDTH_TOO_FAR_RATIO = 0.12f

    /** 肩寬佔畫面寬度高於此比例視為太近。 */
    const val FRAMING_SHOULDER_WIDTH_TOO_CLOSE_RATIO = 0.45f

    /**
     * 手腕 Y 低於畫面高度的此比例視為快被上緣裁掉，提示使用者舉到肩膀即可。
     *
     * ⚠️ 這裡原本還有一個 `FRAMING_SHOULDER_HEADROOM_RATIO = 0.30f`，要求肩膀上方
     * 預留整隻手臂的空間。**已移除，因為它在物理上無法滿足**（2026-10-01 實機發現）：
     * - 直向手機在 2~2.5 公尺拍全身時，肩只落在畫面高度的 0.24~0.29，永遠不過關
     * - 要讓肩超過 0.30 得退到 3 公尺外，那時肩寬只剩 0.21，又快被判「太遠」
     * - 於是「請往後站」與「請往前站」互相拉扯，使用者完全抓不到距離
     *   （當天實測每下之間隔了 18~47 秒，正常應該 3~5 秒）
     * - 更根本：站立 1.70m、雙手舉直約 2.20m，「全身入鏡」與「舉直的手也入鏡」
     *   本來就不可能同時成立
     *
     * 判準既然是「舉到肩高」（p = 1.0），就只需要追蹤到肩高，不需要整隻手都入鏡。
     * 保留這一條貼齊上緣的提醒即可 —— 它只在真的快出框時才出聲，
     * 而不是像前者那樣預先、持續地誤報。
     */
    const val FRAMING_WRIST_NEAR_TOP_RATIO = 0.06f
