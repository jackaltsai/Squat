package com.heartchen.squat.config

/**
 * 集中管理品質控管與狀態機的可調參數，方便之後用驗證集試門檻調參（見 CLAUDE.md 第 6 節）。
 * 目前皆為初始建議值，尚未經實測調參。
 */
object Config {
    /** 關鍵點信心值門檻，低於此值視為不可靠。 */
    const val CONFIDENCE_THRESHOLD = 0.6f

    /** EMA 平滑係數，越大代表越接近原始值（反應快但抖動大），越小代表越平滑（反應慢）。 */
    const val EMA_ALPHA = 0.3f

    /** 深蹲家族：髖部相對站立基準的下降比例（以「髖-踝」垂直距離正規化）超過此值視為開始下蹲。 */
    const val DOWN_ENTER_RATIO = 0.08f

    /** 深蹲家族：髖部下降比例低於此值視為已回到站立高度附近。 */
    const val STAND_RETURN_RATIO = 0.04f

    /** DOWN 狀態下，須連續此幀數滿足「已離開最低點」才確認轉折。 */
    const val TURN_CONFIRM_FRAMES = 3

    /**
     * 轉折確認：髖部須從本次最低點回升超過此比例（以髖-踝距離正規化）才算真的在上升。
     *
     * 舊版的判據是「這一幀比上一幀高」，對連續動作的深蹲可行，但對坐站練習會壞掉：
     * - 長輩從椅子站起來很慢，每幀位移接近雜訊量級，只要一幀沒有嚴格上升計數就歸零，
     *   慢速起身可能永遠確認不了轉折，整下不被計次
     * - 坐到椅面上會停頓，停頓時髖高是平的，隨機雜訊遲早湊出連續幾幀「下降」，
     *   會在人還坐著時就誤觸發最低點
     *
     * 改用「距離最低點的回升量」後，判據與速度無關、也不會被停頓觸發。
     * 這仍然是「轉折點 + 連續幀確認」，不是單一高度閾值（見 CLAUDE.md 第 7 節）：
     * 比較基準是本次動作實際到達的最低點，不是一個固定高度。
     */
    const val TURN_CONFIRM_RISE_RATIO = 0.03f

    /** UP 狀態下，須連續穩定在站立高度附近此幀數才計次並回到 STAND。 */
    const val STAND_STABLE_FRAMES = 5

    /** M3 站姿校正：需連續收集此毫秒數的樣本，取平均作為站立基準髖部高度。 */
    const val STAND_HOLD_DURATION_MS = 3000L

    /** M3 基準深蹲校正：需完成幾次深蹲取平均深度作為 Duser。 */
    const val CALIBRATION_SQUAT_REPS = 2

    /** 校正完成後、正式訓練開始前的倒數秒數（畫面顯示大字並語音念出 3、2、1）。 */
    const val READY_COUNTDOWN_SECONDS = 3

    /**
     * M3 基準深蹲校正品質檢查：兩次校正深蹲的深度全距除以平均，超過此比例視為校正不可信，要求重做。
     *
     * Duser 只取 2 下的平均，只要其中一下試探性地淺蹲，基準就會被拉低，之後每一下的 p 值
     * 都整體偏高、假性達標（2026-09-10 實測：同一人相隔 3 分鐘的兩場，p 平均 0.98 vs 1.25）。
     * 這個門檻是初始值，需後續用驗證集調參。
     */
    const val CALIBRATION_MAX_DEPTH_SPREAD = 0.15f

    /** 校正品質檢查最多重做幾次；超過仍不一致就採用當下結果，避免使用者卡在校正出不去。 */
    const val CALIBRATION_MAX_RETRIES = 2

    /** 框位引導：髖-踝垂直距離佔畫面高度比例，低於此值視為拍攝距離太遠。 */
    const val FRAMING_TOO_FAR_RATIO = 0.20f

    /** 框位引導：髖-踝垂直距離佔畫面高度比例，高於此值視為拍攝距離太近。 */
    const val FRAMING_TOO_CLOSE_RATIO = 0.60f

    /** 框位引導：腳踝 Y 座標超過畫面高度此比例，視為腳踝可能快被裁到畫面外，需請使用者調整。 */
    const val FRAMING_ANKLE_NEAR_EDGE_RATIO = 0.97f

    /** 框位引導：髖部 Y 座標低於畫面高度此比例，視為上半身可能被裁掉，需請使用者調整。 */
    const val FRAMING_HIP_NEAR_TOP_RATIO = 0.08f

    /** 框位引導：同一個問題須連續出現此幀數才算數，避免深蹲快速移動時單幀關鍵點掉點造成誤報。 */
    const val FRAMING_STABLE_FRAMES = 8

    /** M4 膝內夾判定：（踝距 - 膝距）除以髖寬，超過此比例視為膝蓋內夾，需後續用驗證集調參。 */
    const val KNEE_VALGUS_RATIO_THRESHOLD = 0.15f

    /** M4 膝內夾判定：髖寬須至少達腿長的此比例，太小（如側身）視為角度不可靠、不判定。 */
    const val KNEE_VALGUS_MIN_HIP_WIDTH_TO_LEG_RATIO = 0.2f

    // ---- M8 雙臂高舉 ----
    // 手臂動作的進度量級約 1.5~2 個肩寬，深蹲約 0.3 個腿長，差一個數量級，
    // 所以門檻取「判準值（舉到肩高）的比例」而非絕對值。
    // ⚠️ 以下三個與下方框位常數都是推估的初始值，尚未實機調參。

    /** 進度超過判準的此比例視為開始舉手。取 1/4 是為了不被站姿時的手臂自然晃動觸發。 */
    const val ARM_RAISE_ENTER_FRACTION = 0.25f

    /** 須從峰值回退判準的此比例才算轉折（開始放下）。 */
    const val ARM_RAISE_TURN_CONFIRM_FRACTION = 0.08f

    /** 進度低於判準的此比例視為手臂已放回身側，計次 +1。 */
    const val ARM_RAISE_RETURN_FRACTION = 0.15f

    // ---- M8 上肢動作的框位引導 ----
    // 下肢動作用「髖-踝距離佔畫面高度」判斷遠近，上肢動作拿不到腳踝（也不需要），
    // 改用肩寬佔畫面寬度。

    /** 肩寬佔畫面寬度低於此比例視為太遠。 */
    const val FRAMING_SHOULDER_WIDTH_TOO_FAR_RATIO = 0.12f

    /** 肩寬佔畫面寬度高於此比例視為太近。 */
    const val FRAMING_SHOULDER_WIDTH_TOO_CLOSE_RATIO = 0.45f

    /**
     * 手腕 Y 低於畫面高度的此比例視為快被上緣裁掉，提示使用者舉到肩膀即可。
     *
     * ⚠️ 這裡原本還有一個 `FRAMING_SHOULDER_HEADROOM_RATIO = 0.30f`，要求肩膀上方
     * 預留整隻手臂的空間。**已移除，因為它在物理上無法滿足**（2026-10-01 實機發現）：
     * - 直向手機在 2~2.5 公尺拍全身時，肩只落在畫面高度的 0.24~0.29，永遠不過關
     * - 要讓肩超過 0.30 得退到 3 公尺外，那時肩寬只剩 0.21，又快被判「太遠」
     * - 於是「請往後站」與「請往前站」互相拉扯，使用者完全抓不到距離
     *   （當天實測每下之間隔了 18~47 秒，正常應該 3~5 秒）
     * - 更根本：站立 1.70m、雙手舉直約 2.20m，「全身入鏡」與「舉直的手也入鏡」
     *   本來就不可能同時成立
     *
     * 判準既然是「舉到肩高」（p = 1.0），就只需要追蹤到肩高，不需要整隻手都入鏡。
     * 保留這一條貼齊上緣的提醒即可 —— 它只在真的快出框時才出聲，
     * 而不是像前者那樣預先、持續地誤報。
     */
    const val FRAMING_WRIST_NEAR_TOP_RATIO = 0.06f
}
